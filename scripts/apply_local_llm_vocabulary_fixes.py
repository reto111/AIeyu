def backup_db(db_path: Path) -> Path:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    target = BACKUP_DIR / f"{db_path.stem}_before_local_llm_vocab_fixes_{stamp}.sqlite"
    shutil.copy2(db_path, target)
    return target


def apply_fixes(db_path: Path, dry_run: bool) -> tuple[Path | None, Path, dict[str, int]]:
    backup_path = None if dry_run else backup_db(db_path)
    report_path = REPORT_DIR / f"local_llm_vocabulary_fixes_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    stats = {"updated": 0, "skipped_unchanged": 0, "skipped_missing": 0, "skipped_changed": 0, "skipped_collision": 0}
    rows: list[dict[str, str]] = []

    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    try:
        for item_id, expected_word, word, part_of_speech, meaning_zh, reason in FIXES:
            current = conn.execute(
                "SELECT id, word, lemma, part_of_speech, meaning_zh FROM vocabulary_items WHERE id = ?",
                (item_id,),
            ).fetchone()
            status = "updated"
            if not current:
                status = "skipped_missing"
            elif current["word"] != expected_word:
                status = "skipped_changed"
            elif (
                current["word"] == word
                and (current["part_of_speech"] or "") == (part_of_speech or "")
                and current["meaning_zh"] == meaning_zh
            ):
                status = "skipped_unchanged"
            else:
                collision = conn.execute(
                    """
                    SELECT id FROM vocabulary_items
                    WHERE id <> ?
                      AND word = ?
                      AND COALESCE(part_of_speech, '') = COALESCE(?, '')
                    LIMIT 1
                    """,
                    (item_id, word, part_of_speech),
                ).fetchone()
                if collision:
                    status = "skipped_collision"
                elif not dry_run:
                    conn.execute(
                        """
                        UPDATE vocabulary_items
                        SET word = ?, lemma = ?, part_of_speech = ?, meaning_zh = ?, updated_at = CURRENT_TIMESTAMP
                        WHERE id = ?
                        """,
                        (word, word, part_of_speech or None, meaning_zh, item_id),
                    )
            stats[status] += 1
            rows.append(
                {
                    "id": str(item_id),
                    "status": status,
                    "old_word": current["word"] if current else "",
                    "old_part_of_speech": current["part_of_speech"] if current else "",
                    "old_meaning_zh": current["meaning_zh"] if current else "",
                    "new_word": word,
                    "new_part_of_speech": part_of_speech,
                    "new_meaning_zh": meaning_zh,
                    "reason": reason,
                }
            )
        if not dry_run:
            conn.commit()
    finally:
        conn.close()

    with report_path.open("w", encoding="utf-8-sig", newline="") as f:
        fieldnames = [
            "id",
            "status",
            "old_word",
            "old_part_of_speech",
            "old_meaning_zh",
            "new_word",
            "new_part_of_speech",
            "new_meaning_zh",
            "reason",
        ]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    return backup_path, report_path, stats


def main() -> None:
    parser = argparse.ArgumentParser(description="Apply conservative local-LLM vocabulary fixes.")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    backup_path, report_path, stats = apply_fixes(args.db, args.dry_run)
    print(f"backup={backup_path or ''}")
    print(f"report={report_path}")
    for key, value in stats.items():
        print(f"{key}={value}")


if __name__ == "__main__":
    main()
